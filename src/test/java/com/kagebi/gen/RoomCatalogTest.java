/**
 * Holds every room file on disk to the contract the game reads it by.
 *
 * <p>The rooms are generated by tools/make_maps.py, which checks most of this
 * itself - but they are also meant to be opened in Tiled and finished by hand,
 * and a hand edit is exactly how a crate ends up in a doorway or a layer ends
 * up renamed. So the checks live here too, where they run on every build
 * whoever last touched the file.
 *
 * <p>Two readers on purpose. {@link RoomCatalog} is what the game uses, and it
 * is forgiving: an object type it does not recognise is silently skipped. So
 * the raw XML is read separately here, and anything the catalog would drop is
 * a failure rather than a room that quietly has no chest in it.
 */
class RoomCatalogTest {

    private static final File ROOMS = new File("assets/maps/rooms");

    /**
     * The folder names, which are also the {@code FloorDef.biome} strings in
     * floors.json. Pinned here because they are load-bearing across a
     * boundary: rename a folder and every floor that names it silently falls
     * back to borrowed rooms, which only shows up as the wrong tileset.
     */
    private static final Set<String> BIOMES =
        Set.of("ruins", "ruins_green", "ruins_orange", "depths");

    private static final String[] LAYERS = {
        TiledRooms.GROUND, TiledRooms.DRESSING, TiledRooms.DECOR,
        TiledRooms.WALLS, TiledRooms.PROPS, TiledRooms.OVERHEAD,
    };

    private static final int W = RoomTemplate.WIDTH;
    private static final int H = RoomTemplate.HEIGHT;
    /** Tiled keeps flip and rotation flags in the top four bits of a gid. */
    private static final int GID_MASK = 0x0FFFFFFF;

    private static Array<RoomTemplate> catalog;
    private static final Map<String, Tmx> files = new TreeMap<>();

    @BeforeAll
    static void readEverything() {
        assertTrue(ROOMS.isDirectory(), "no " + ROOMS + " - run: python tools/make_maps.py");
        catalog = RoomCatalog.load(new FileHandle(ROOMS));
        for (File biome : ROOMS.listFiles(File::isDirectory)) {
            for (File f : biome.listFiles((d, n) -> n.endsWith(".tmx"))) {
                String id = biome.getName() + "/" + f.getName().replace(".tmx", "");
                files.put(id, new Tmx(f));
            }
        }
    }

    // ---- the catalog ------------------------------------------------------

    @Test
    void everyFileOnDiskIsInTheCatalog() {
        Set<String> ids = new HashSet<>();
        for (RoomTemplate t : catalog) {
            ids.add(t.id);
        }
        assertEquals(files.keySet(), ids);
    }

    @Test
    void theBiomesAreExactlyTheFoldersFloorsJsonNames() {
        Set<String> found = new HashSet<>();
        for (RoomTemplate t : catalog) {
            found.add(t.biome);
        }
        assertEquals(BIOMES, found);
    }

    @Test
    void everyBiomeHasTwentyRoomsAndEveryKind() {
        for (String biome : BIOMES) {
            int n = 0;
            Set<RoomKind> kinds = new HashSet<>();
            for (RoomTemplate t : catalog) {
                if (t.biome.equals(biome)) {
                    n++;
                    for (RoomKind k : t.kinds) {
                        kinds.add(k);
                    }
                }
            }
            assertTrue(n >= 20, biome + " has only " + n + " rooms");
            assertEquals(Set.of(RoomKind.values()), kinds, biome + " is missing a kind");
        }
    }

    @Test
    void theFileNamePrefixNamesExactlyOneKind() {
        // RoomCatalog falls back to NORMAL+START for a prefix it does not
        // know, which is the right runtime behaviour and the wrong thing to
        // let a typo do silently.
        for (RoomTemplate t : catalog) {
            // Split on the slash first: biome names have underscores in them
            // too (ruins_green), which is fine for RoomCatalog - it only ever
            // sees the file name - and a trap for anything parsing the id.
            String name = t.id.substring(t.id.indexOf('/') + 1);
            String prefix = name.substring(0, name.indexOf('_'));
            assertEquals(1, t.kinds.size, t.id + " suits " + t.kinds);
            assertEquals(prefix.toUpperCase(), t.kinds.first().name(), t.id);
        }
    }

    // ---- shape -------------------------------------------------------------

    @Test
    void everyRoomIsTwentyByEleven() {
        for (Map.Entry<String, Tmx> e : files.entrySet()) {
            Tmx m = e.getValue();
            assertEquals(W, m.width, e.getKey());
            assertEquals(H, m.height, e.getKey());
            assertEquals(16, m.tileWidth, e.getKey());
            assertEquals(16, m.tileHeight, e.getKey());
            for (Map.Entry<String, int[]> layer : m.layers.entrySet()) {
                assertEquals(W * H, layer.getValue().length, e.getKey() + " layer " + layer.getKey());
            }
        }
    }

    @Test
    void layersAreTheOnesTheRendererDraws() {
        for (Map.Entry<String, Tmx> e : files.entrySet()) {
            assertEquals(Arrays.asList(LAYERS), new ArrayList<>(e.getValue().layers.keySet()),
                e.getKey() + " layer names or order");
            assertEquals(List.of("spawns"), e.getValue().objectGroups, e.getKey());
        }
    }

    /**
     * The two overlay layers stop nobody, and the human's is painted last.
     *
     * <p>Both halves are one line to get wrong and expensive to notice. Making
     * {@code dressing} blocking turns every skull scattered on the crypt floor
     * into an invisible obstacle - the player is stopped by something that
     * plainly is not in the way. Ordering {@code decor} under {@code dressing}
     * means a tile someone placed by hand in Tiled can be covered by generated
     * debris, which is the same as losing the work.
     */
    @Test
    void theOverlayLayersBlockNothingAndTheHandDrawnOneIsOnTop() {
        assertFalse(TiledRooms.blocks(TiledRooms.DRESSING));
        assertFalse(TiledRooms.blocks(TiledRooms.DECOR));
        assertTrue(TiledRooms.blocks(TiledRooms.WALLS));
        assertTrue(TiledRooms.blocks(TiledRooms.PROPS));

        List<String> below = Arrays.asList(TiledRooms.BELOW);
        assertTrue(below.indexOf(TiledRooms.DRESSING) < below.indexOf(TiledRooms.DECOR),
            "decor is the human's layer and must paint over the generator's");
        assertTrue(below.indexOf(TiledRooms.GROUND) < below.indexOf(TiledRooms.DRESSING));
    }

    /** The generator owns dressing, so unlike decor it is checked for content. */
    @Test
    void theCryptFloorsAreDressed() {
        int dressed = 0;
        for (Map.Entry<String, Tmx> e : files.entrySet()) {
            if (!e.getKey().startsWith("depths/")) {
                continue;
            }
            for (int gid : e.getValue().layers.get(TiledRooms.DRESSING)) {
                if ((gid & GID_MASK) != 0) {
                    dressed++;
                }
            }
        }
        assertTrue(dressed >= 200, "only " + dressed + " bones across the depths; "
            + "its floor is one flat purple and has nothing else to read against");
    }

    // Deliberately no "decor is empty" test. The generator never writes decor,
    // but decor is where a human finishes a room in Tiled, so an emptiness
    // test would fail the build on exactly the work the layer exists for.
    // What must hold whoever drew them - every decor tile resolves to a real
    // tileset - is covered below, flip bits and hand-added tilesets included.

    @Test
    void everyTileIdBelongsToATileset() {
        // A gid past the end of a tileset renders as nothing in libGDX - no
        // error, just a hole in the wall - so it is checked rather than seen.
        for (Map.Entry<String, Tmx> e : files.entrySet()) {
            Tmx m = e.getValue();
            for (Map.Entry<String, int[]> layer : m.layers.entrySet()) {
                for (int raw : layer.getValue()) {
                    int gid = raw & GID_MASK;
                    if (gid != 0) {
                        assertTrue(m.owns(gid), e.getKey() + " " + layer.getKey() + " gid " + gid);
                    }
                }
            }
        }
    }

    @Test
    void tilesetImagesExistAndMatchTheirDeclaredSize() throws IOException {
        // If a tileset image is ever re-exported at a different width, every
        // gid past the first row points at a different tile. The .tmx cannot
        // notice; this can.
        Assumptions.assumeTrue(new File("assets/gfx/tiles").isDirectory(),
            "tilesets not built - run: python tools/build_assets.py");
        Map<File, int[]> seen = new HashMap<>();
        for (Map.Entry<String, Tmx> e : files.entrySet()) {
            for (Tileset ts : e.getValue().tilesets) {
                File img = ts.image.getCanonicalFile();
                assertTrue(img.isFile(), e.getKey() + ": missing " + ts.image);
                int[] size = seen.get(img);
                if (size == null) {
                    BufferedImage bi = ImageIO.read(img);
                    size = new int[] {bi.getWidth(), bi.getHeight()};
                    seen.put(img, size);
                }
                assertEquals(size[0], ts.imageWidth, e.getKey() + " " + ts.name + " width");
                assertEquals(size[1], ts.imageHeight, e.getKey() + " " + ts.name + " height");
                assertEquals(size[0] / 16, ts.columns, e.getKey() + " " + ts.name + " columns");
                assertEquals((size[0] / 16) * (size[1] / 16), ts.tileCount,
                    e.getKey() + " " + ts.name + " tile count");
            }
        }
    }

    // ---- doors and floor ---------------------------------------------------

    @Test
    void allFourDoorwaysAreOpen() {
        for (Map.Entry<String, Tmx> e : files.entrySet()) {
            boolean[][] solid = e.getValue().solid();
            for (int[] c : doorCells()) {
                assertFalse(solid[c[1]][c[0]], e.getKey() + ": doorway blocked at " + c[0] + "," + c[1]);
            }
        }
    }

    @Test
    void everyDoorReachesEveryOtherDoorAndAllTheFloor() {
        // An open doorway that leads into a sealed pocket still looks open in
        // a preview; only a flood fill tells them apart.
        for (Map.Entry<String, Tmx> e : files.entrySet()) {
            boolean[][] solid = e.getValue().solid();
            int[] start = doorCells().get(0);
            boolean[][] seen = new boolean[H][W];
            Deque<int[]> todo = new ArrayDeque<>();
            seen[start[1]][start[0]] = true;
            todo.add(start);
            while (!todo.isEmpty()) {
                int[] c = todo.poll();
                int[][] steps = {{1, 0}, {-1, 0}, {0, 1}, {0, -1}};
                for (int[] s : steps) {
                    int x = c[0] + s[0], y = c[1] + s[1];
                    if (x >= 0 && y >= 0 && x < W && y < H && !solid[y][x] && !seen[y][x]) {
                        seen[y][x] = true;
                        todo.add(new int[] {x, y});
                    }
                }
            }
            for (int y = 0; y < H; y++) {
                for (int x = 0; x < W; x++) {
                    assertTrue(solid[y][x] || seen[y][x],
                        e.getKey() + ": floor at " + x + "," + y + " cannot be reached");
                }
            }
        }
    }

    // ---- spawns -------------------------------------------------------------

    @Test
    void everySpawnTypeIsASpawnPointKindSpelledExactly() {
        Set<String> kinds = new HashSet<>();
        for (SpawnPoint.Kind k : SpawnPoint.Kind.values()) {
            kinds.add(k.name());
        }
        for (Map.Entry<String, Tmx> e : files.entrySet()) {
            for (Obj o : e.getValue().objects) {
                assertTrue(kinds.contains(o.type), e.getKey() + ": unknown spawn type '" + o.type + "'");
            }
        }
        // And the catalog kept every one of them.
        for (RoomTemplate t : catalog) {
            assertEquals(files.get(t.id).objects.size(), t.spawns.size, t.id + " dropped spawns");
        }
    }

    @Test
    void everySpawnStandsOnOpenFloor() {
        for (Map.Entry<String, Tmx> e : files.entrySet()) {
            boolean[][] solid = e.getValue().solid();
            for (Obj o : e.getValue().objects) {
                if ("PROP".equals(o.type)) {
                    continue;   // wall dressing; see the test below
                }
                int tx = (int) Math.floor(o.x / 16), ty = (int) Math.floor(o.y / 16);
                assertTrue(tx >= 0 && ty >= 0 && tx < W && ty < H, e.getKey() + ": " + o + " outside the room");
                assertFalse(solid[ty][tx], e.getKey() + ": " + o + " is inside a wall or a prop");
            }
        }
    }

    /**
     * Wall dressing obeys the opposite rule, and it is asserted rather than
     * merely exempted.
     *
     * <p>A torch is bracketed to stone, so it belongs on a cell that is solid -
     * which is also what makes it free: the cell already blocked the player, so
     * no torch can ever narrow a room or stand in the open to be walked
     * through. Letting PROP off the floor rule without pinning the inverse
     * would have allowed exactly that, and a torch standing in the middle of
     * the floor with the player passing through it is precisely what the first
     * cut of this produced.
     */
    @Test
    void everyWallPropIsBracketedToStoneAndClearOfTheDoors() {
        int found = 0;
        for (Map.Entry<String, Tmx> e : files.entrySet()) {
            boolean[][] solid = e.getValue().solid();
            for (Obj o : e.getValue().objects) {
                if (!"PROP".equals(o.type)) {
                    continue;
                }
                found++;
                int tx = (int) Math.floor(o.x / 16), ty = (int) Math.floor(o.y / 16);
                assertTrue(tx >= 0 && ty >= 0 && tx < W && ty < H,
                    e.getKey() + ": " + o + " outside the room");
                assertTrue(tx == 0 || ty == 0 || tx == W - 1 || ty == H - 1,
                    e.getKey() + ": " + o + " is not on the perimeter");
                assertTrue(solid[ty][tx],
                    e.getKey() + ": " + o + " hangs on open floor, so the player walks through it");
                for (int[] door : doorCells()) {
                    assertFalse(door[0] == tx && door[1] == ty,
                        e.getKey() + ": " + o + " blocks a doorway");
                }
                // The top row belongs to the HUD. The heart bar runs along it
                // from the left and lengthens as maximum health is bought, and
                // the minimap covers the right; a torch up there is paid for
                // and never seen, which is what the first pass placed.
                assertNotEquals(0, ty, e.getKey() + ": " + o + " is on the top wall, under the HUD");
            }
        }
        assertTrue(found >= 200, "only " + found + " wall props across " + files.size()
            + " rooms; every room is meant to be lit");
    }

    @Test
    void entriesSitBesideTheDoorTheyAreNamedFor() {
        // Read through the catalog, so this is in the game's y-up space: it is
        // the test that fails if the y flip in RoomCatalog ever goes the wrong
        // way, which would put the player at the opposite door on every entry.
        int edge = 3 * 16;
        for (RoomTemplate t : catalog) {
            Map<String, SpawnPoint> entries = new HashMap<>();
            for (SpawnPoint s : t.spawns) {
                if (s.kind == SpawnPoint.Kind.ENTRY && s.tag != null) {
                    assertFalse(entries.containsKey(s.tag), t.id + ": two entries tagged " + s.tag);
                    entries.put(s.tag, s);
                }
            }
            assertEquals(Set.of("UP", "DOWN", "LEFT", "RIGHT"), entries.keySet(), t.id);
            assertTrue(entries.get("UP").y > RoomTemplate.PIXEL_HEIGHT - edge, t.id + " UP " + entries.get("UP"));
            assertTrue(entries.get("DOWN").y < edge, t.id + " DOWN " + entries.get("DOWN"));
            assertTrue(entries.get("LEFT").x < edge, t.id + " LEFT " + entries.get("LEFT"));
            assertTrue(entries.get("RIGHT").x > RoomTemplate.PIXEL_WIDTH - edge, t.id + " RIGHT " + entries.get("RIGHT"));
        }
    }

    @Test
    void eachRoomCarriesWhatItsKindNeeds() {
        for (RoomTemplate t : catalog) {
            Map<SpawnPoint.Kind, Integer> n = new HashMap<>();
            boolean bossTagged = false;
            for (SpawnPoint s : t.spawns) {
                n.merge(s.kind, 1, Integer::sum);
                bossTagged |= s.kind == SpawnPoint.Kind.ENEMY && "boss".equals(s.tag);
            }
            int enemies = n.getOrDefault(SpawnPoint.Kind.ENEMY, 0);
            switch (t.kinds.first()) {
                case START:
                    assertEquals(0, enemies, t.id + ": the start room must be safe");
                    break;
                case NORMAL:
                    assertTrue(enemies > 0, t.id + ": a fight room with nothing to fight");
                    break;
                case BOSS:
                    assertTrue(bossTagged && enemies == 1, t.id + ": wants exactly one enemy, tagged boss");
                    break;
                case EXIT:
                    assertTrue(n.getOrDefault(SpawnPoint.Kind.EXIT, 0) == 1, t.id + ": no stairs");
                    break;
                case SHOP:
                    assertTrue(n.getOrDefault(SpawnPoint.Kind.SHOPKEEPER, 0) == 1, t.id + ": no shopkeeper");
                    break;
                default:
                    assertTrue(n.getOrDefault(SpawnPoint.Kind.CHEST, 0) >= 1, t.id + ": no chest");
            }
        }
    }

    // ---- helpers ----------------------------------------------------------

    /** The twelve tiles of the four openings, in Tiled's y-down rows. */
    private static List<int[]> doorCells() {
        List<int[]> cells = new ArrayList<>();
        for (int i = 0; i < RoomTemplate.DOOR_SPAN; i++) {
            cells.add(new int[] {RoomTemplate.DOOR_X + i, 0});
            cells.add(new int[] {RoomTemplate.DOOR_X + i, H - 1});
            cells.add(new int[] {0, RoomTemplate.DOOR_Y + i});
            cells.add(new int[] {W - 1, RoomTemplate.DOOR_Y + i});
        }
        return cells;
    }

    private static final class Tileset {
        String name;
        int firstGid, tileCount, columns, imageWidth, imageHeight;
        File image;
    }

    private static final class Obj {
        String type, name;
        float x, y;

        @Override
        public String toString() {
            return type + "(" + name + ")@" + x + "," + y;
        }
    }

    /** One .tmx read straight from its XML, y-down, exactly as Tiled wrote it. */
    private static final class Tmx {
        final int width, height, tileWidth, tileHeight;
        final List<Tileset> tilesets = new ArrayList<>();
        final Map<String, int[]> layers = new java.util.LinkedHashMap<>();
        final List<String> objectGroups = new ArrayList<>();
        final List<Obj> objects = new ArrayList<>();

        Tmx(File file) {
            XmlReader.Element map = new XmlReader().parse(new FileHandle(file));
            width = map.getIntAttribute("width");
            height = map.getIntAttribute("height");
            tileWidth = map.getIntAttribute("tilewidth");
            tileHeight = map.getIntAttribute("tileheight");
            for (XmlReader.Element ts : map.getChildrenByName("tileset")) {
                Tileset t = new Tileset();
                t.name = ts.getAttribute("name");
                t.firstGid = ts.getIntAttribute("firstgid");
                t.tileCount = ts.getIntAttribute("tilecount");
                t.columns = ts.getIntAttribute("columns");
                XmlReader.Element img = ts.getChildByName("image");
                t.image = new File(file.getParentFile(), img.getAttribute("source"));
                t.imageWidth = img.getIntAttribute("width");
                t.imageHeight = img.getIntAttribute("height");
                tilesets.add(t);
            }
            for (XmlReader.Element layer : map.getChildrenByName("layer")) {
                String[] cells = layer.getChildByName("data").getText().trim().split("\\s*,\\s*");
                int[] gids = new int[cells.length];
                for (int i = 0; i < cells.length; i++) {
                    gids[i] = (int) Long.parseLong(cells[i].trim());
                }
                layers.put(layer.getAttribute("name"), gids);
            }
            for (XmlReader.Element group : map.getChildrenByName("objectgroup")) {
                objectGroups.add(group.getAttribute("name"));
                for (XmlReader.Element o : group.getChildrenByName("object")) {
                    Obj obj = new Obj();
                    obj.type = o.getAttribute("type", "");
                    obj.name = o.getAttribute("name", "");
                    obj.x = o.getFloatAttribute("x");
                    obj.y = o.getFloatAttribute("y");
                    objects.add(obj);
                }
            }
        }

        boolean owns(int gid) {
            for (Tileset t : tilesets) {
                if (gid >= t.firstGid && gid < t.firstGid + t.tileCount) {
                    return true;
                }
            }
            return false;
        }

        /** Exactly the layers TiledRooms treats as blocking; asked, not copied. */
        boolean[][] solid() {
            boolean[][] s = new boolean[height][width];
            for (String name : LAYERS) {
                if (!TiledRooms.blocks(name)) {
                    continue;
                }
                int[] g = layers.get(name);
                for (int i = 0; i < g.length; i++) {
                    if ((g[i] & GID_MASK) != 0) {
                        s[i / width][i % width] = true;
                    }
                }
            }
            return s;
        }
    }
}
